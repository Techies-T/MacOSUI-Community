USE testdb;

DROP TABLE IF EXISTS batting_stats;
DROP TABLE IF EXISTS pitching_stats;
DROP TABLE IF EXISTS games;
DROP TABLE IF EXISTS team_standings;
DROP TABLE IF EXISTS players;
DROP TABLE IF EXISTS teams;

-- 1. Teams Master Table
CREATE TABLE teams (
    team_id VARCHAR(10) PRIMARY KEY,
    team_name VARCHAR(50) NOT NULL,
    league VARCHAR(20) NOT NULL, -- 'Central' or 'Pacific'
    wins INT NOT NULL DEFAULT 0,
    losses INT NOT NULL DEFAULT 0,
    draws INT NOT NULL DEFAULT 0,
    win_rate DECIMAL(4, 3) NOT NULL DEFAULT 0.000,
    games_behind DECIMAL(3, 1) NOT NULL DEFAULT 0.0,
    runs_scored INT NOT NULL DEFAULT 0,
    runs_allowed INT NOT NULL DEFAULT 0
);

-- 2. Team Standings Table (Multi-Year 2024 & 2025 Official Final Records)
CREATE TABLE team_standings (
    id INT AUTO_INCREMENT PRIMARY KEY,
    team_id VARCHAR(10) NOT NULL,
    team_name VARCHAR(50) NOT NULL,
    league VARCHAR(20) NOT NULL, -- 'Central' or 'Pacific'
    year INT NOT NULL,           -- 2024 or 2025
    wins INT NOT NULL DEFAULT 0,
    losses INT NOT NULL DEFAULT 0,
    draws INT NOT NULL DEFAULT 0,
    win_rate DECIMAL(4, 3) NOT NULL DEFAULT 0.000,
    games_behind DECIMAL(3, 1) NOT NULL DEFAULT 0.0,
    runs_scored INT NOT NULL DEFAULT 0,
    runs_allowed INT NOT NULL DEFAULT 0,
    INDEX idx_year_league (year, league),
    INDEX idx_team_year (team_id, year),
    FOREIGN KEY (team_id) REFERENCES teams(team_id)
);

-- 3. Players Table
CREATE TABLE players (
    player_id INT AUTO_INCREMENT PRIMARY KEY,
    team_id VARCHAR(10) NOT NULL,
    name VARCHAR(50) NOT NULL,
    position VARCHAR(20) NOT NULL,
    bats_throws VARCHAR(20) NOT NULL,
    INDEX idx_team (team_id),
    FOREIGN KEY (team_id) REFERENCES teams(team_id)
);

-- 4. Batting Stats Table (Multi-Year, WAR, WAA, Sabermetrics)
CREATE TABLE batting_stats (
    id INT AUTO_INCREMENT PRIMARY KEY,
    player_id INT NOT NULL,
    year INT NOT NULL,           -- 2024 or 2025
    at_bats INT NOT NULL,
    hits INT NOT NULL,
    home_runs INT NOT NULL,
    rbi INT NOT NULL,
    risp_at_bats INT NOT NULL DEFAULT 0,
    risp_hits INT NOT NULL DEFAULT 0,
    risp_avg DECIMAL(4, 3) NOT NULL DEFAULT 0.000, -- 得点圏打率
    batting_avg DECIMAL(4, 3) NOT NULL,
    obp DECIMAL(4, 3) NOT NULL, -- 出塁率
    slg DECIMAL(4, 3) NOT NULL, -- 長打率
    ops DECIMAL(4, 3) NOT NULL, -- OPS
    woba DECIMAL(4, 3) NOT NULL, -- wOBA
    walks INT NOT NULL DEFAULT 0, -- 四球
    strikeouts INT NOT NULL DEFAULT 0, -- 三振
    war DECIMAL(3, 1) NOT NULL DEFAULT 0.0, -- WAR (総合勝利寄与度)
    waa DECIMAL(3, 1) NOT NULL DEFAULT 0.0, -- WAA (平均以上勝利数)
    title_awards VARCHAR(100) DEFAULT NULL, -- 獲得タイトル・表彰
    INDEX idx_player_year (player_id, year),
    INDEX idx_year_war (year, war),
    INDEX idx_year_waa (year, waa),
    FOREIGN KEY (player_id) REFERENCES players(player_id)
);

-- 5. Pitching Stats Table (Multi-Year, WAR, WAA, FIP, WHIP, ERA)
CREATE TABLE pitching_stats (
    id INT AUTO_INCREMENT PRIMARY KEY,
    player_id INT NOT NULL,
    year INT NOT NULL,           -- 2024 or 2025
    games INT NOT NULL DEFAULT 0,
    games_started INT NOT NULL DEFAULT 0,
    wins INT NOT NULL DEFAULT 0,
    losses INT NOT NULL DEFAULT 0,
    saves INT NOT NULL DEFAULT 0,
    holds INT NOT NULL DEFAULT 0,
    innings_pitched DECIMAL(4, 1) NOT NULL DEFAULT 0.0, -- 投球回
    hits_allowed INT NOT NULL DEFAULT 0,
    runs_allowed INT NOT NULL DEFAULT 0,
    earned_runs INT NOT NULL DEFAULT 0,
    home_runs_allowed INT NOT NULL DEFAULT 0,
    walks INT NOT NULL DEFAULT 0,
    strikeouts INT NOT NULL DEFAULT 0,
    era DECIMAL(4, 2) NOT NULL DEFAULT 0.00,  -- 防御率
    whip DECIMAL(4, 2) NOT NULL DEFAULT 0.00, -- WHIP
    fip DECIMAL(4, 2) NOT NULL DEFAULT 0.00,  -- FIP (真の防御率能力)
    war DECIMAL(3, 1) NOT NULL DEFAULT 0.0,  -- 投手WAR
    waa DECIMAL(3, 1) NOT NULL DEFAULT 0.0,  -- 投手WAA
    title_awards VARCHAR(100) DEFAULT NULL,   -- タイトル・表彰
    INDEX idx_player_year (player_id, year),
    INDEX idx_year_war (year, war),
    INDEX idx_year_waa (year, waa),
    FOREIGN KEY (player_id) REFERENCES players(player_id)
);

-- 6. Games Table
CREATE TABLE games (
    id INT AUTO_INCREMENT PRIMARY KEY,
    game_date DATE NOT NULL,
    season_year INT NOT NULL,
    home_team VARCHAR(10) NOT NULL,
    away_team VARCHAR(10) NOT NULL,
    home_score INT NOT NULL,
    away_score INT NOT NULL,
    stadium VARCHAR(50) NOT NULL,
    winning_pitcher VARCHAR(50),
    losing_pitcher VARCHAR(50),
    FOREIGN KEY (home_team) REFERENCES teams(team_id),
    FOREIGN KEY (away_team) REFERENCES teams(team_id)
);

